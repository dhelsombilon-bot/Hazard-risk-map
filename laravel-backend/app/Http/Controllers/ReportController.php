<?php

namespace App\Http\Controllers;

use App\Models\Barangay;
use App\Models\Building;
use App\Models\Permit;
use App\Models\PermitFinding;
use App\Models\Report;
use App\Services\XlsxWriter;
use Illuminate\Http\Request;
use Illuminate\Support\Carbon;
use Illuminate\Support\Str;

class ReportController extends Controller
{
    /** Timestamps are stored in UTC; reports show local (Philippine) time. */
    private const DISPLAY_TZ = 'Asia/Manila';
    private const TITLES = [
        'permit_compliance' => 'Permit Compliance Summary',
        'hazard_exposure' => 'Hazard Exposure Report',
        'inventory_summary' => 'Building Inventory Summary',
        'inspection_findings' => 'Inspection Findings Log',
    ];

    public function index()
    {
        $reports = Report::with('generator')->orderByDesc('generated_at')->orderByDesc('report_id')->get();

        return response()->json($reports->map(fn ($r) => [
            'report_id' => $r->report_id,
            'report_type' => $r->report_type,
            'report_title' => self::TITLES[$r->report_type] ?? Str::headline($r->report_type),
            'generated_by' => $r->generator ? trim($r->generator->first_name.' '.$r->generator->last_name) : '',
            'generated_at' => $r->generated_at,
            'parameters' => $r->parameters,
            'file_url' => $r->file_url,
        ]));
    }

    public function preview(Request $request)
    {
        $type = $request->get('report_type', 'permit_compliance');
        $report = $this->buildReport($type, $request->only(['barangay_id', 'date_from', 'date_to']));
        $report['table_data'] = $report['table_data']->take(20)->values();

        return response()->json($report);
    }

    public function generate(Request $request)
    {
        $data = $request->validate(['report_type' => 'required|string']);

        $report = Report::create([
            'report_type' => $data['report_type'],
            'generated_by' => $request->user()->user_id,
            'generated_at' => now(),
            'parameters' => array_filter($request->only(['barangay_id', 'date_from', 'date_to']), fn ($v) => $v !== null && $v !== ''),
        ]);

        return response()->json([
            'report_id' => $report->report_id,
            'report_type' => $report->report_type,
            'report_title' => self::TITLES[$report->report_type] ?? Str::headline($report->report_type),
            'generated_at' => $report->generated_at,
            'file_url' => null,
        ], 201);
    }

    /**
     * Download a generated report as a formatted Excel (.xlsx) file.
     * The data is rebuilt from the report's saved type and filter parameters.
     */
    public function download($id)
    {
        $report = Report::with('generator')->findOrFail($id);
        $params = array_filter($report->parameters ?? [], fn ($v) => $v !== null && $v !== '');
        $built = $this->buildReport($report->report_type, $params);
        $rows = $built['table_data']->map(fn ($r) => array_map(fn ($v) => $v ?? '', $r))->values();

        $generatedAt = $report->generated_at?->copy()->timezone(self::DISPLAY_TZ);
        $generatedBy = $report->generator ? trim($report->generator->first_name.' '.$report->generator->last_name) : '—';
        $barangay = isset($params['barangay_id'])
            ? (Barangay::find($params['barangay_id'])?->barangay_name ?? $params['barangay_id'])
            : 'All barangays';
        $dateFrom = isset($params['date_from']) ? Carbon::parse($params['date_from'])->format('M j, Y') : null;
        $dateTo = isset($params['date_to']) ? Carbon::parse($params['date_to'])->format('M j, Y') : null;
        $period = match (true) {
            $dateFrom && $dateTo => "$dateFrom – $dateTo",
            (bool) $dateFrom => "From $dateFrom",
            (bool) $dateTo => "Up to $dateTo",
            default => 'All dates',
        };

        $columns = $rows->isNotEmpty() ? array_keys($rows->first()) : ['records'];
        $colCount = max(count($columns), 2);

        $x = new XlsxWriter($built['title']);
        $L = XlsxWriter::STYLE_LABEL;
        $D = XlsxWriter::STYLE_DEFAULT;

        $r = $x->addRow([$built['title']], XlsxWriter::STYLE_TITLE);
        $x->merge($r, 1, $colCount);
        $r = $x->addRow(['GeoPermit – Public Building Permit & Hazard Monitoring System'], XlsxWriter::STYLE_SUBTITLE);
        $x->merge($r, 1, $colCount);
        $x->addRow([]);
        $x->addRow(['Report No.', $report->report_id], [$L, $D]);
        $x->addRow(['Generated on', $generatedAt?->format('F j, Y g:i A') ?? '—'], [$L, $D]);
        $x->addRow(['Generated by', $generatedBy], [$L, $D]);
        $x->addRow(['Barangay', $barangay], [$L, $D]);
        $x->addRow(['Period', $period], [$L, $D]);
        $x->addRow([]);

        // Summary
        $x->addRow(['Summary'], XlsxWriter::STYLE_SECTION);
        $x->addRow(['Category', 'Count'], XlsxWriter::STYLE_HEADER);
        $total = 0;
        foreach ($built['chart_data'] as $c) {
            $value = (int) ($c['value'] ?? 0);
            $total += $value;
            $x->addRow([(string) ($c['name'] ?? 'Unknown'), $value], XlsxWriter::STYLE_CELL);
        }
        $x->addRow(['Total', $total], XlsxWriter::STYLE_TOTAL);
        $x->addRow([]);

        // Records
        $x->addRow(['Records ('.$rows->count().')'], XlsxWriter::STYLE_SECTION);
        $headerRow = $x->addRow(array_map(fn ($k) => Str::headline($k), $columns), XlsxWriter::STYLE_HEADER);
        if ($rows->isEmpty()) {
            $x->addRow(['No records found for the selected filters.'], XlsxWriter::STYLE_CELL);
        }
        foreach ($rows as $row) {
            $last = $x->addRow(array_values($row), XlsxWriter::STYLE_CELL);
        }
        if ($rows->isNotEmpty()) {
            $x->autoFilter($headerRow, 1, count($columns), $last);
        }

        // Column widths: fit the longest value per column (capped), wide enough for labels
        $headerLabels = ['Generated on', 'Category'];
        for ($i = 0; $i < $colCount; $i++) {
            $values = $rows->pluck($columns[$i] ?? null)->filter()->map(fn ($v) => mb_strlen((string) $v));
            $longest = max($values->max() ?? 0, mb_strlen(Str::headline($columns[$i] ?? '')), $i === 0 ? 14 : 10);
            if ($i === 1) {
                $longest = max($longest, mb_strlen($generatedAt?->format('F j, Y g:i A') ?? ''), mb_strlen($barangay), mb_strlen($period));
            }
            $x->setWidth($i + 1, min($longest + 3, 60));
        }

        $path = $x->save();
        $filename = Str::slug($built['title']).'-no'.$report->report_id.'-'.($generatedAt?->format('Y-m-d') ?? 'report').'.xlsx';

        return response()->download($path, $filename, [
            'Content-Type' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        ])->deleteFileAfterSend(true);
    }

    private function buildReport(string $type, array $params): array
    {
        $barangayId = $params['barangay_id'] ?? null;
        $dateFrom = $params['date_from'] ?? null;
        $dateTo = $params['date_to'] ?? null;

        if ($type === 'inventory_summary') {
            $buildings = Building::with(['barangay', 'buildingType'])
                ->when($barangayId, fn ($q) => $q->where('barangay_id', $barangayId))
                ->get();

            return [
                'title' => self::TITLES[$type],
                'chart_type' => 'bar',
                'chart_data' => $buildings->groupBy(fn ($b) => $b->buildingType?->type_name ?? 'Other')
                    ->map(fn ($g, $k) => ['name' => $k, 'value' => $g->count()])->values(),
                'table_data' => $buildings->map(fn ($b) => [
                    'building_code' => $b->building_code,
                    'building_name' => $b->building_name,
                    'barangay' => $b->barangay?->barangay_name,
                    'type' => $b->buildingType?->type_name,
                ])->values(),
            ];
        }

        if ($type === 'hazard_exposure') {
            $buildings = Building::with(['hazardAssessments', 'barangay'])
                ->when($barangayId, fn ($q) => $q->where('barangay_id', $barangayId))
                ->get();

            return [
                'title' => self::TITLES[$type],
                'chart_type' => 'pie',
                'chart_data' => $buildings->groupBy(fn ($b) => $b->risk_level ?: 'Unknown')
                    ->map(fn ($g, $k) => ['name' => $k, 'value' => $g->count()])->values(),
                'table_data' => $buildings->map(fn ($b) => [
                    'building_name' => $b->building_name,
                    'barangay' => $b->barangay?->barangay_name,
                    'risk_level' => $b->risk_level,
                ])->values(),
            ];
        }

        if ($type === 'inspection_findings') {
            $findings = PermitFinding::with(['permit.building.barangay'])
                ->when($barangayId, fn ($q) => $q->whereHas('permit.building', fn ($bq) => $bq->where('barangay_id', $barangayId)))
                ->when($dateFrom, fn ($q) => $q->whereDate('created_at', '>=', $dateFrom))
                ->when($dateTo, fn ($q) => $q->whereDate('created_at', '<=', $dateTo))
                ->get();

            return [
                'title' => self::TITLES[$type],
                'chart_type' => 'bar',
                'chart_data' => $findings->groupBy(fn ($f) => $f->status ?: 'Unknown')
                    ->map(fn ($g, $k) => ['name' => $k, 'value' => $g->count()])->values(),
                'table_data' => $findings->map(fn ($f) => [
                    'permit_number' => $f->permit?->permit_number,
                    'building' => $f->permit?->building?->building_name,
                    'severity' => $f->severity,
                    'description' => $f->description,
                    'status' => $f->status,
                    'resolved_at' => optional($f->resolved_at)->format('Y-m-d'),
                ])->values(),
            ];
        }

        // Default: permit compliance
        $permits = Permit::with(['permitStatus', 'permitType', 'building.barangay'])
            ->when($barangayId, fn ($q) => $q->whereHas('building', fn ($bq) => $bq->where('barangay_id', $barangayId)))
            ->when($dateFrom, fn ($q) => $q->whereDate('created_at', '>=', $dateFrom))
            ->when($dateTo, fn ($q) => $q->whereDate('created_at', '<=', $dateTo))
            ->get();

        return [
            'title' => self::TITLES['permit_compliance'],
            'chart_type' => 'pie',
            'chart_data' => $permits->groupBy(fn ($p) => $p->permit_status ?: 'Unknown')
                ->map(fn ($g, $k) => ['name' => $k, 'value' => $g->count()])->values(),
            'table_data' => $permits->map(fn ($p) => [
                'permit_number' => $p->permit_number,
                'building' => $p->building?->building_name,
                'type' => $p->permit_type,
                'status' => $p->permit_status,
            ])->values(),
        ];
    }
}
